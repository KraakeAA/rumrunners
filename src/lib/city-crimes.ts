// The job as it appears in the given city: new name, description and scene,
// with the original pay, risk and rank untouched.
export function crimeForCity(crime: CrimeDef, city: string | null | undefined): CrimeDef {
  const entry = CITY_CRIMES[city ?? ""]?.[crime.id] ?? CITY_CRIMES.London[crime.id];
  if (!entry) return crime;
  const base = crime.scenes[0];
  const scenes: CrimeScene[] = entry.scene
    ? [{ ...entry.scene, risk: base.risk, pay: base.pay }]
    : crime.scenes;
  return { ...crime, name: entry.name, description: entry.description, scenes };
}
